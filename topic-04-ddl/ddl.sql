-- MEMBERSHIP MANAGEMENT
-- RESPONSIBLE OLEH SVYRYDENKO
-- =========================================================

-- Versioned membership products.
-- Prices are never edited in place — when a price changes, a new row
-- is inserted with a new valid_from and the old row gets a valid_to date.
-- This preserves full price history and ensures members_memberships rows
-- always point to the exact price that was active at signup.
--
-- Query for currently active products: WHERE valid_to IS NULL
CREATE TABLE gym.memberships (
    membership_id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    type          gym.membership_type NOT NULL,

    -- DECIMAL(10,2) supports values up to 99,999,999.99.
    -- Negative prices are nonsensical and blocked by the check.
    price         DECIMAL(10,2) NOT NULL CHECK (price > 0),

    -- ISO 4217 three-letter currency code (e.g. 'UAH', 'EUR', 'USD').
    -- CHAR(3) enforces the exact length at the DB level.
    currency      CHAR(3) NOT NULL DEFAULT 'UAH',

    valid_from    DATE NOT NULL,

    -- NULL means this product version is currently active.
    valid_to      DATE,

    -- Prevents a product version from ending before it starts.
    CONSTRAINT chk_memberships_date_range
        CHECK (valid_to IS NULL OR valid_to >= valid_from)
);

-- A person registered as a gym member.
-- UNIQUE on person_id enforces the 1-to-1 relationship with persons.
-- Membership history is tracked in members_memberships, not here.
CREATE TABLE gym.members (
    member_id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    person_id BIGINT UNIQUE NOT NULL,

    CONSTRAINT fk_members_person
        FOREIGN KEY (person_id) REFERENCES gym.persons(person_id)
);

-- Records which membership product a member enrolled in and when.
-- Supports full history: a member can have multiple rows over time
-- (renewals, upgrades, lapses). The membership_id FK points to the
-- exact versioned product row, implicitly snapshotting the price.
CREATE TABLE gym.members_memberships (
    members_membership_id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    membership_id         BIGINT NOT NULL,
    member_id             BIGINT NOT NULL,
    start_date            DATE NOT NULL,

    -- NULL means the enrollment is open-ended (no defined expiry).
    end_date              DATE,

    -- Percentage discount applied at signup. 0 = no discount, 100 = free.
    -- Stored as an integer; fractional discounts are not supported.
    discount              INTEGER DEFAULT 0 CHECK (discount BETWEEN 0 AND 100),

    CONSTRAINT fk_mm_membership
        FOREIGN KEY (membership_id) REFERENCES gym.memberships(membership_id),
    CONSTRAINT fk_mm_member
        FOREIGN KEY (member_id) REFERENCES gym.members(member_id),

    -- Prevents an enrollment from ending before it begins.
    CONSTRAINT chk_mm_date_range
        CHECK (end_date IS NULL OR end_date >= start_date)
);

-- Records a member's booking or physical presence at a class session.
-- One row per member per session.
--
-- check_in_time is NULL until the member physically arrives.
-- It remains NULL for no_show and cancelled records.
CREATE TABLE gym.attendance (
    attendance_id     BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    member_id         BIGINT NOT NULL,
    class_schedule_id BIGINT NOT NULL,

    -- Nullable: populated on physical arrival, NULL for no_show / cancelled.
    check_in_time     TIMESTAMPTZ,

    status            gym.attendance_status NOT NULL,

    CONSTRAINT fk_attendance_member
        FOREIGN KEY (member_id) REFERENCES gym.members(member_id),
    CONSTRAINT fk_attendance_schedule
        FOREIGN KEY (class_schedule_id) REFERENCES gym.class_schedule(class_schedule_id)
);

-- =========================================================
-- EQUIPMENT AND GOAL TRACKING
-- RESPONSIBLE DMYTRO TOKARIYEV
-- =========================================================

-- Gym equipment inventory. Not linked to scheduling —
-- used for maintenance tracking and operational status only.
CREATE TABLE gym.equipment (
    equipment_id     BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    name             VARCHAR(150) NOT NULL,

    -- Defaults to 'available' on insert.
    -- Use UPDATE to transition: available → under_repair → available / broken.
    status           gym.equipment_status NOT NULL DEFAULT 'available',

    -- NULL means maintenance has never been recorded.
    -- Cannot be a future date — maintenance must have already happened.
    last_maintenance DATE,

    CONSTRAINT ck_equipment_maintenance_not_future
        CHECK (last_maintenance IS NULL OR last_maintenance <= CURRENT_DATE)
);

-- A fitness goal set by a member.
-- target_value and current_state in progress are both VARCHAR to support
-- any goal type: numeric (e.g. '80 kg'), qualitative ('run 5k'), or habit-based.
CREATE TABLE gym.goals (
    goal_id          BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    member_id        BIGINT NOT NULL,
    goal_description VARCHAR(255) NOT NULL,

    -- Optional free-text target. Examples: '75', '5km', '20 pull-ups'.
    target_value     VARCHAR(100),

    -- Optional target date for the goal.
    -- Lower bound of 2000-01-01 is a sanity check against data entry errors.
    deadline         DATE,

    -- Defaults to 'in_progress' on creation.
    status           gym.goal_status NOT NULL DEFAULT 'in_progress',

    created_at       DATE NOT NULL DEFAULT CURRENT_DATE,

    CONSTRAINT ck_goals_deadline
        CHECK (deadline IS NULL OR deadline >= '2000-01-01')
);

-- A timestamped check-in entry against a goal.
-- Multiple entries per goal build a progress timeline.
--
-- ON DELETE CASCADE — deleting a goal also deletes all its progress records.
-- UNIQUE (goal_id, check_date) — only one progress entry per goal per day.
--   To update today's entry, UPDATE the existing row rather than inserting a new one.
CREATE TABLE gym.progress (
    progress_id   BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    goal_id       BIGINT NOT NULL,

    -- Free-text snapshot of current state. Examples: '78.5', 'completed week 3'.
    current_state VARCHAR(255) NOT NULL,
    notes         VARCHAR(500),
    check_date    DATE NOT NULL DEFAULT CURRENT_DATE,

    CONSTRAINT fk_progress_goal
        FOREIGN KEY (goal_id) REFERENCES gym.goals(goal_id)
        ON DELETE CASCADE,

    -- One entry per goal per day. Inserting a second entry for the same day
    -- will raise a unique violation — use UPDATE instead.
    CONSTRAINT uq_progress_goal_date
        UNIQUE (goal_id, check_date)
);

-- =========================================================
-- PERSONAL TRAINING MANAGEMENT
-- RESPONSIBLE ANDREW CHERNUHA
-- =========================================================

-- One-on-one sessions booked between a member and a trainer,
-- outside the group class scheduling system.
--
-- uq_member_time  — a member cannot have two personal sessions at the same time.
-- uq_trainer_time — a trainer cannot run two personal sessions at the same time.
-- Note: these constraints do not cross-check against class_schedule.
--       Conflict detection between personal training and group classes
--       must be handled at the application layer.
CREATE TABLE gym.personal_training (
    session_id    BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    member_id     BIGINT NOT NULL,
    trainer_id    BIGINT NOT NULL,
    training_date TIMESTAMPTZ NOT NULL,
    status        gym.personal_training_status NOT NULL DEFAULT 'scheduled',

    CONSTRAINT fk_personal_training_member
        FOREIGN KEY (member_id) REFERENCES gym.members(member_id),
    CONSTRAINT fk_personal_training_trainer
        FOREIGN KEY (trainer_id) REFERENCES gym.trainers(trainer_id),

    -- Prevents double-booking a member at the same timestamp.
    CONSTRAINT uq_member_time
        UNIQUE (member_id, training_date),

    -- Prevents double-booking a trainer at the same timestamp.
    CONSTRAINT uq_trainer_time
        UNIQUE (trainer_id, training_date)
);

-- Regular weekly working hours for a trainer.
-- Used by the application to validate that scheduled sessions
-- fall within a trainer's available hours.
--
-- uq_trainer_day — one schedule row per trainer per weekday.
--   To change hours for a day, UPDATE the existing row; do not insert a duplicate.
-- is_active = FALSE allows suspending a day without deleting the row,
--   preserving history and making reactivation a simple UPDATE.
CREATE TABLE gym.trainer_work_schedule (
    work_schedule_id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    trainer_id       BIGINT NOT NULL,
    day_of_week      gym.day_of_week NOT NULL,
    start_time       TIME NOT NULL,
    end_time         TIME NOT NULL,

    -- Prevents a shift from ending before or at its start time.
    CONSTRAINT chk_work_schedule_time_range
        CHECK (end_time > start_time),

    is_active        BOOLEAN DEFAULT TRUE,

    CONSTRAINT fk_work_schedule_trainer
        FOREIGN KEY (trainer_id) REFERENCES gym.trainers(trainer_id),

    -- One active schedule row per trainer per weekday.
    CONSTRAINT uq_trainer_day
        UNIQUE (trainer_id, day_of_week)
);

-- Leave requests for trainers (sick days, vacation, personal).
-- The application should cross-reference approved leave records
-- when generating class_schedule rows to flag conflicts.
--
-- Limitation: chk_leaves_date_range allows end_date = NULL (open-ended leave),
-- but the CHECK only fires when end_date IS NOT NULL.
-- Open-ended leaves must be closed explicitly via UPDATE.
CREATE TABLE gym.trainer_leaves (
    leave_id   BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    trainer_id BIGINT NOT NULL,
    leave_type gym.leave_type NOT NULL,
    start_date DATE NOT NULL,

    -- NULL means the leave has no defined end date (e.g. extended sick leave).
    end_date   DATE,

    status     gym.leave_status NOT NULL,
    notes      VARCHAR(500),

    CONSTRAINT fk_leaves_trainer
        FOREIGN KEY (trainer_id) REFERENCES gym.trainers(trainer_id),

    -- Prevents end date from preceding start date when end_date is provided.
    CONSTRAINT chk_leaves_date_range
        CHECK (end_date >= start_date)
);

