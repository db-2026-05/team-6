COMMENT ON SCHEMA gym IS 'Gym management system schema';

-- persons
COMMENT ON TABLE  gym.persons IS 'Base identity record for every person in the system. Members and trainers extend this via a 1-to-1 FK. Business tables never reference person_id directly.';
COMMENT ON COLUMN gym.persons.email IS 'Optional. RFC 5321 max length of 254 chars. Validated by ck_person_email_format.';
COMMENT ON COLUMN gym.persons.phone IS 'Required. Stored as text to preserve leading + sign. Validated by ck_person_phone_format.';
COMMENT ON COLUMN gym.persons.birth_date IS 'Optional. Must be between 1900-01-01 and yesterday. Validated by ck_person_birth_date.';

-- trainers
COMMENT ON TABLE  gym.trainers IS 'A person employed as a trainer. Extends persons via a 1-to-1 relationship.';
COMMENT ON COLUMN gym.trainers.hire_date IS 'Cannot be in the future. Defaults to CURRENT_DATE on insert.';

-- specializations
COMMENT ON TABLE gym.specializations IS 'Catalogue of trainer qualification types. Rows should not be deleted once assigned — deactivate at application level instead.';

-- trainer_specializations
COMMENT ON TABLE gym.trainer_specializations IS 'Many-to-many: which specializations a trainer holds. Composite PK prevents duplicates. Cascade-deletes when trainer is removed; restricts delete of an assigned specialization.';

-- rooms
COMMENT ON TABLE  gym.rooms IS 'Physical spaces where classes and personal training take place.';
COMMENT ON COLUMN gym.rooms.capacity IS 'Minimum 2. NULL means no defined capacity limit.';

-- class_templates
COMMENT ON TABLE  gym.class_templates IS 'Catalogue of class types. No scheduling data lives here — only the definition of what a class is.';
COMMENT ON COLUMN gym.class_templates.capacity IS 'Overrides room capacity when set. NULL defers to the room capacity.';

-- class_recurrence_rules
COMMENT ON TABLE  gym.class_recurrence_rules IS 'Master repeating assignment: trainer + class + room + pattern. Day details live in rule_week_days (weekly) or rule_month_days (monthly). Daily rules need no day table.';
COMMENT ON COLUMN gym.class_recurrence_rules.frequency IS 'Determines which day-detail table applies: weekly → rule_week_days, monthly → rule_month_days, daily → neither.';

-- rule_week_days
COMMENT ON TABLE  gym.rule_week_days IS 'Days of the week for weekly recurrence rules. One row per day. Cascade-deletes when the parent rule is removed.';

-- rule_month_days
COMMENT ON TABLE  gym.rule_month_days IS 'Days of the month for monthly recurrence rules. One row per day. Days 29-31 may not exist in every month — the application must skip non-existent dates when materializing sessions.';

-- class_schedule
COMMENT ON TABLE  gym.class_schedule IS 'Materialized individual sessions generated from recurrence rules by a background job. class_id, trainer_id, and room_id are denormalized from the rule to support per-session overrides without modifying the master rule.';
COMMENT ON COLUMN gym.class_schedule.start_datetime IS 'Stored in UTC (TIMESTAMPTZ). Local time conversion is handled at the application layer.';
COMMENT ON COLUMN gym.class_schedule.end_datetime IS 'Must be strictly greater than start_datetime. Stored in UTC.';

-- memberships
COMMENT ON TABLE  gym.memberships IS 'Versioned membership products. Never edit a row — insert a new one when the price changes and set valid_to on the old row. Query WHERE valid_to IS NULL for currently active products.';
COMMENT ON COLUMN gym.memberships.currency IS 'ISO 4217 three-letter code. CHAR(3) enforces exact length. Defaults to UAH.';
COMMENT ON COLUMN gym.memberships.valid_to IS 'NULL means this product version is currently active.';

-- members
COMMENT ON TABLE gym.members IS 'A person registered as a gym member. Membership history is in members_memberships. UNIQUE on person_id enforces 1-to-1 with persons.';

-- members_memberships
COMMENT ON TABLE  gym.members_memberships IS 'Enrollment history: which versioned membership product a member signed up for and when. Multiple rows per member support renewals, upgrades, and lapses.';
COMMENT ON COLUMN gym.members_memberships.membership_id IS 'Points to the exact versioned product row, implicitly snapshotting the price at signup.';
COMMENT ON COLUMN gym.members_memberships.discount IS 'Percentage discount (0–100). Integer only — fractional discounts are not supported.';
COMMENT ON COLUMN gym.members_memberships.end_date IS 'NULL means the enrollment is open-ended.';

-- attendance
COMMENT ON TABLE  gym.attendance IS 'One row per member per class session. Tracks booking and physical check-in.';
COMMENT ON COLUMN gym.attendance.check_in_time IS 'NULL until the member physically arrives. Remains NULL for no_show and cancelled records.';

-- equipment
COMMENT ON TABLE  gym.equipment IS 'Gym equipment inventory. Not linked to scheduling — used for maintenance tracking only.';
COMMENT ON COLUMN gym.equipment.last_maintenance IS 'NULL means maintenance has never been recorded. Cannot be a future date.';

-- goals
COMMENT ON TABLE  gym.goals IS 'Fitness goals created by members. target_value is free-text to support numeric, distance, and habit-based goals.';
COMMENT ON COLUMN gym.goals.target_value IS 'Free-text target. Examples: ''75'', ''5km'', ''20 pull-ups''. No unit enforcement.';

-- progress
COMMENT ON TABLE  gym.progress IS 'Timestamped check-in entries against a goal. One entry per goal per day (uq_progress_goal_date). To update today''s entry, use UPDATE — a second INSERT on the same day will raise a unique violation. Cascade-deletes with the parent goal.';

-- personal_training
COMMENT ON TABLE  gym.personal_training IS 'One-on-one sessions outside the group class system. uq_member_time and uq_trainer_time prevent double-booking, but cross-checking against class_schedule is the application''s responsibility.';

-- trainer_work_schedule
COMMENT ON TABLE  gym.trainer_work_schedule IS 'Regular weekly availability for each trainer. One row per trainer per weekday (uq_trainer_day). Set is_active = FALSE to suspend a day without losing history.';

-- trainer_leaves
COMMENT ON TABLE  gym.trainer_leaves IS 'Leave requests for trainers. Approved leaves should be checked by the scheduling layer before generating class_schedule rows. Open-ended leaves (end_date IS NULL) must be closed via UPDATE.';
COMMENT ON COLUMN gym.trainer_leaves.end_date IS 'NULL means the leave has no defined end date (e.g. extended sick leave). Must be closed explicitly.';
